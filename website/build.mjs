import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const srcDir = path.join(__dirname, 'src');
const distDir = path.join(__dirname, 'dist');

function readVersion() {
  const propsPath = path.join(repoRoot, 'gradle.properties');
  const props = fs.readFileSync(propsPath, 'utf8');
  const match = props.match(/^VERSION_NAME\s*=\s*(.+)$/m);
  if (!match) {
    throw new Error('Could not find VERSION_NAME in gradle.properties');
  }
  return match[1].trim();
}

function toCamelCase(key) {
  const parts = key.replace(/\./g, '_').split('_');
  return parts[0] + parts.slice(1).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

function formatFloat32Array(values) {
  const chunks = [];
  for (let i = 0; i < values.length; i += 8) {
    chunks.push('  ' + values.slice(i, i + 8).join(', '));
  }
  if (chunks.length === 1) {
    return `new Float32Array([${values.join(', ')}])`;
  }
  return `new Float32Array([\n${chunks.join(',\n')}\n])`;
}

function generateWeightsModule() {
  const jsonPath = path.join(repoRoot, 'scripts', 'data', 'pigments_mlp.json');
  const raw = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));

  const lines = [
    '// Auto-generated by website/build.mjs from scripts/data/pigments_mlp.json — do not edit manually.',
    '',
  ];

  for (const [key, value] of Object.entries(raw)) {
    const jsName = toCamelCase(key);
    const flat = Array.isArray(value[0]) ? value.flat() : value;
    lines.push(`export const ${jsName} = ${formatFloat32Array(flat)};`);
    lines.push('');
  }

  return lines.join('\n');
}

function generatePigmentsMixModule() {
  const ktPath = path.join(
    repoRoot,
    'vibrance',
    'src',
    'commonMain',
    'kotlin',
    'dev',
    'romainguy',
    'vibrance',
    'Vibrance.kt'
  );
  const ktSource = fs.readFileSync(ktPath, 'utf8');

  const signatureIdx = ktSource.indexOf('internal fun pigmentsMixLinear(');
  if (signatureIdx === -1) {
    throw new Error('Could not locate internal fun pigmentsMixLinear in Vibrance.kt');
  }
  const openBraceIdx = ktSource.indexOf('{', signatureIdx);
  let depth = 0;
  let closeBraceIdx = -1;
  for (let i = openBraceIdx; i < ktSource.length; i++) {
    if (ktSource[i] === '{') depth++;
    else if (ktSource[i] === '}') {
      depth--;
      if (depth === 0) {
        closeBraceIdx = i;
        break;
      }
    }
  }
  if (closeBraceIdx === -1) {
    throw new Error('Unbalanced braces in pigmentsMixLinear');
  }

  const ktBody = ktSource.slice(openBraceIdx + 1, closeBraceIdx);
  const jsBody = ktBody
    .replace(/\r\n/g, '\n')
    .replace(/\bval\b/g, 'const')
    .replace(/\bvar\b/g, 'let')
    .replace(/\bmax\s*\(/g, 'Math.max(')
    .replace(/([rgb])\.fastCoerceIn\(\s*0\.0f\s*,\s*1\.0f\s*\)/g, 'clamp01($1)')
    .replace(/(\d)f\b/g, '$1');

  return [
    '// Auto-generated by website/build.mjs from Vibrance.kt — do not edit manually.',
    '',
    'function clamp01(v) {',
    '  return v < 0.0 ? 0.0 : v > 1.0 ? 1.0 : v;',
    '}',
    '',
    'export function pigmentsMixLinear(c0, c1, c2, color) {',
    jsBody.trimEnd(),
    '}',
    '',
  ].join('\n');
}

function copyDirectory(source, destination, replacements) {
  fs.mkdirSync(destination, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const srcPath = path.join(source, entry.name);
    const dstPath = path.join(destination, entry.name);
    if (entry.isDirectory()) {
      copyDirectory(srcPath, dstPath, replacements);
    } else if (entry.name.endsWith('.html')) {
      let content = fs.readFileSync(srcPath, 'utf8');
      for (const [token, value] of Object.entries(replacements)) {
        content = content.replaceAll(token, value);
      }
      fs.writeFileSync(dstPath, content);
    } else {
      fs.copyFileSync(srcPath, dstPath);
    }
  }
}

const version = readVersion();

fs.rmSync(distDir, { recursive: true, force: true });
copyDirectory(srcDir, distDir, { '{{VERSION}}': version });

const jsDistDir = path.join(distDir, 'js');
fs.mkdirSync(jsDistDir, { recursive: true });
fs.writeFileSync(path.join(jsDistDir, 'weights.js'), generateWeightsModule());
fs.writeFileSync(path.join(jsDistDir, 'pigments-mix.js'), generatePigmentsMixModule());

console.log(`Built website into website/dist (Vibrance v${version}).`);

const verifyResult = spawnSync(process.execPath, [path.join(__dirname, 'verify.mjs')], {
  stdio: 'inherit',
});
if (verifyResult.status !== 0) {
  process.exit(verifyResult.status ?? 1);
}
